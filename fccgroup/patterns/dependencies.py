"""
Dependency graph between SMARTS fingerprints.

Callable fingerprints read the results of other fingerprints through ``row["Name"]``
(e.g. ``Alkanes`` reads ``Aliphatic hydrocarbons``). The dependencies are never declared,
so they are discovered here by inspecting the string constants of each callable's
bytecode. Line breaks, whitespace and comments do not matter since the compiled code
object is inspected, not the source text.

The graph is generated by ``scripts/build_fingerprint_graph.py`` into
``_dependency_graph.py`` and checked for staleness in the tests and in the publish
workflow. Dependencies that cannot be detected statically (e.g. keys built with
f-strings) go in ``MANUAL_DEPENDENCIES``.
"""

import types
from typing import Callable, Dict, Iterable, List, Mapping, Set, Union

Fingerprints = Mapping[str, Union[str, Callable]]
DependencyGraph = Dict[str, Set[str]]

# Dependencies that cannot be inferred from the bytecode: {fingerprint: {dependency, ...}}
MANUAL_DEPENDENCIES: DependencyGraph = {}


def _referenced_strings(code: types.CodeType) -> Set[str]:
    """Collect string constants of a code object, including nested lambdas/comprehensions."""
    found: Set[str] = set()

    def collect(const) -> None:
        if isinstance(const, str):
            found.add(const)
        elif isinstance(const, types.CodeType):
            found.update(_referenced_strings(const))
        elif isinstance(const, (tuple, frozenset)):  # folded list/set literals
            for item in const:
                collect(item)

    for const in code.co_consts:
        collect(const)
    return found


def extract_dependencies(fps: Fingerprints) -> DependencyGraph:
    """Build ``{fingerprint: direct dependencies}`` from the fingerprint definitions."""
    names = set(fps)
    graph: DependencyGraph = {}
    for name, pattern in fps.items():
        deps: Set[str] = set()
        code = getattr(pattern, "__code__", None)
        if code is not None:
            deps |= _referenced_strings(code) & names
        deps |= set(MANUAL_DEPENDENCIES.get(name, ()))
        deps.discard(name)
        graph[name] = deps
    return graph


def find_cycle(graph: Mapping[str, Iterable[str]]) -> List[str]:
    """Return one dependency cycle as a list of names, or an empty list if acyclic."""
    WHITE, GREY, BLACK = 0, 1, 2
    state: Dict[str, int] = {}

    def visit(node: str, path: List[str]) -> List[str]:
        state[node] = GREY
        path.append(node)
        for dep in graph.get(node, ()):
            if state.get(dep, WHITE) == GREY:
                return path[path.index(dep):] + [dep]
            if state.get(dep, WHITE) == WHITE:
                cycle = visit(dep, path)
                if cycle:
                    return cycle
        path.pop()
        state[node] = BLACK
        return []

    for start in graph:
        if state.get(start, WHITE) == WHITE:
            cycle = visit(start, [])
            if cycle:
                return cycle
    return []


def resolve_dependencies(
    selected: Iterable[str],
    graph: Mapping[str, Iterable[str]],
) -> Set[str]:
    """Return ``selected`` plus all of its transitive dependencies."""
    closure: Set[str] = set()
    stack = list(selected)
    while stack:
        name = stack.pop()
        if name in closure:
            continue
        closure.add(name)
        stack.extend(graph.get(name, ()))
    return closure


def misordered(fps: Fingerprints, graph: Mapping[str, Iterable[str]]) -> List[str]:
    """Return names defined before one of their dependencies (empty when order is valid)."""
    position = {name: i for i, name in enumerate(fps)}
    return [
        name
        for name, deps in graph.items()
        if any(position[dep] > position[name] for dep in deps)
    ]


def dependency_order(
    names: Iterable[str],
    graph: Mapping[str, Iterable[str]],
    definition_order: Iterable[str],
) -> List[str]:
    """Order ``names`` so every fingerprint comes after its dependencies.

    Follows the definition order wherever it is already valid; a fingerprint is only
    moved later than its definition position when it precedes one of its dependencies.
    """
    wanted = set(names)
    ordered: List[str] = []
    placed: Set[str] = set()

    def place(name: str) -> None:
        if name in placed:
            return
        placed.add(name)
        for dep in sorted(graph.get(name, ()), key=position.__getitem__):
            if dep in wanted:
                place(dep)
        ordered.append(name)

    position = {name: i for i, name in enumerate(definition_order)}
    for name in sorted(wanted, key=position.__getitem__):
        place(name)
    return ordered


def render_graph_module(graph: Mapping[str, Iterable[str]]) -> str:
    """Render the graph as the source of ``_dependency_graph.py`` (deterministic output)."""
    lines = [
        '"""Generated by scripts/build_fingerprint_graph.py. Do not edit by hand."""',
        "",
        "FINGERPRINT_DEPENDENCIES = {",
    ]
    for name in sorted(graph):
        deps = sorted(graph[name])
        if deps:
            lines.append(f"    {name!r}: {deps!r},")
    lines += ["}", ""]
    return "\n".join(lines)
